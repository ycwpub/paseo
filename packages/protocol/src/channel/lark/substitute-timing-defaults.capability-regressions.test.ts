import { describe, expect, test } from "vitest";
import {
  DEFAULT_LARK_SUBSTITUTE_DELAY_SECONDS,
  DEFAULT_LARK_SUBSTITUTE_GROUP_SCAN_EXCLUDE_RECENT_MINUTES,
  DEFAULT_LARK_SUBSTITUTE_GROUP_SCAN_INTERVAL_MINUTES,
  DEFAULT_LARK_SUBSTITUTE_GROUP_SCAN_LOOKBACK_MINUTES,
  DEFAULT_LARK_SUBSTITUTE_PRIVATE_SCAN_EXCLUDE_RECENT_MINUTES,
  DEFAULT_LARK_SUBSTITUTE_PRIVATE_SCAN_INTERVAL_MINUTES,
  DEFAULT_LARK_SUBSTITUTE_PRIVATE_SCAN_LOOKBACK_MINUTES,
} from "./substitute-types.js";

describe("Lark substitute timing defaults", () => {
  test("keeps scan timing separate from realtime debounce", () => {
    expect(DEFAULT_LARK_SUBSTITUTE_DELAY_SECONDS).toBe(600);
    expect(DEFAULT_LARK_SUBSTITUTE_GROUP_SCAN_INTERVAL_MINUTES).toBe(30);
    expect(DEFAULT_LARK_SUBSTITUTE_GROUP_SCAN_LOOKBACK_MINUTES).toBe(60);
    expect(DEFAULT_LARK_SUBSTITUTE_GROUP_SCAN_EXCLUDE_RECENT_MINUTES).toBe(10);
    expect(DEFAULT_LARK_SUBSTITUTE_PRIVATE_SCAN_INTERVAL_MINUTES).toBe(30);
    expect(DEFAULT_LARK_SUBSTITUTE_PRIVATE_SCAN_LOOKBACK_MINUTES).toBe(60);
    expect(DEFAULT_LARK_SUBSTITUTE_PRIVATE_SCAN_EXCLUDE_RECENT_MINUTES).toBe(10);
  });
});
