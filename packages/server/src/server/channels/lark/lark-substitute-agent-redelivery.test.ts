import type { LarkSubstituteTask } from "@getpaseo/protocol/messages";
import { describe, expect, test, vi } from "vitest";
import type { AgentManagerEvent } from "../../agent/agent-manager.js";
import {
  isLarkSubstituteRedeliveryRequest,
  LarkSubstituteAgentRedelivery,
} from "./lark-substitute-agent-redelivery.js";

function task(agentId: string): LarkSubstituteTask {
  return {
    id: "task-1",
    modeId: "mode-1",
    modeName: "替身",
    botId: "bot-1",
    source: "group_listener",
    status: "completed",
    stage: null,
    chatId: "oc_1",
    chatName: "群聊",
    messageId: "om_1",
    senderOpenId: "ou_1",
    senderName: "用户",
    content: "问题",
    agentId,
    error: null,
    createdAt: "2026-09-10T00:00:00.000Z",
    updatedAt: "2026-09-10T00:00:01.000Z",
  };
}

function userMessage(agentId: string, text: string, turnId = "turn-1"): AgentManagerEvent {
  return {
    type: "agent_stream",
    agentId,
    event: {
      type: "timeline",
      provider: "codex",
      turnId,
      item: {
        type: "user_message",
        text,
        clientMessageId: "client-1",
      },
    },
  };
}

function completed(agentId: string, turnId = "turn-1"): AgentManagerEvent {
  return {
    type: "agent_stream",
    agentId,
    event: { type: "turn_completed", provider: "codex", turnId },
  };
}

function createHarness(options: { tasks?: LarkSubstituteTask[]; messages?: Array<string | null> }) {
  const messages = [...(options.messages ?? ["最终答案"])];
  const send = vi.fn(async () => undefined);
  const redelivery = new LarkSubstituteAgentRedelivery({
    listTasks: () => options.tasks ?? [task("agent-1")],
    getLastAssistantMessage: vi.fn(async () => messages.shift() ?? null),
    send,
    warn: vi.fn(),
    error: vi.fn(),
  });
  return { redelivery, send };
}

describe("isLarkSubstituteRedeliveryRequest", () => {
  test.each([
    "把最新回答，重新通过飞书发送给用户",
    "请把修正后的内容重发给原用户",
    "send the updated answer to the original user in Lark",
  ])("recognizes explicit delivery request: %s", (text) => {
    expect(isLarkSubstituteRedeliveryRequest(text)).toBe(true);
  });

  test.each([
    "重新生成一个更准确的回答",
    "解释一下为什么没有发送",
    "<lark_substitute_trigger>Reply to the user in Lark</lark_substitute_trigger>",
  ])("ignores non-delivery or generated task prompts: %s", (text) => {
    expect(isLarkSubstituteRedeliveryRequest(text)).toBe(false);
  });
});

describe("LarkSubstituteAgentRedelivery", () => {
  test("sends the answer generated by the matching turn", async () => {
    const harness = createHarness({ messages: ["新回答"] });

    await harness.redelivery.handle(userMessage("agent-1", "把最新回答，重新通过飞书发送给用户"));
    await harness.redelivery.handle(completed("agent-1"));

    expect(harness.send).toHaveBeenCalledWith("agent-1", "新回答");
  });

  test("resends the latest existing answer when the turn does not change its text", async () => {
    const harness = createHarness({ messages: ["已有最新回答"] });

    await harness.redelivery.handle(userMessage("agent-1", "把最新回答，重新通过飞书发送给用户"));
    await harness.redelivery.handle(completed("agent-1"));

    expect(harness.send).toHaveBeenCalledWith("agent-1", "已有最新回答");
  });

  test("does not send for a regular Project Agent", async () => {
    const harness = createHarness({ tasks: [], messages: ["新回答"] });

    await harness.redelivery.handle(userMessage("agent-1", "把最新回答，重新通过飞书发送给用户"));
    await harness.redelivery.handle(completed("agent-1"));

    expect(harness.send).not.toHaveBeenCalled();
  });

  test("does not duplicate a reply already sent through the CLI during the turn", async () => {
    const harness = createHarness({ messages: ["命令执行完成"] });

    await harness.redelivery.handle(userMessage("agent-1", "把最新回答，重新通过飞书发送给用户"));
    harness.redelivery.noteDelivered("agent-1");
    await harness.redelivery.handle(completed("agent-1"));

    expect(harness.send).not.toHaveBeenCalled();
  });

  test("waits for the requested turn instead of sending an earlier queued turn", async () => {
    const harness = createHarness({ messages: ["新回答"] });

    await harness.redelivery.handle(
      userMessage("agent-1", "把最新回答，重新通过飞书发送给用户", "turn-2"),
    );
    await harness.redelivery.handle(completed("agent-1", "turn-1"));
    expect(harness.send).not.toHaveBeenCalled();

    await harness.redelivery.handle(completed("agent-1", "turn-2"));
    expect(harness.send).toHaveBeenCalledWith("agent-1", "新回答");
  });
});
